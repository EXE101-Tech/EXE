// Hàm tìm tọa độ từ chuỗi địa chỉ
export function findVenueCoordinates(locationStr) {
  if (!locationStr || typeof locationStr !== 'string') return null;

  // 1. Kiểm tra nếu trong chuỗi có cặp số tọa độ "(lat, lon)"
  const match = locationStr.match(/(-?\d+\.\d+)\s*,\s*(-?\d+\.\d+)/);
  if (match) {
    const lat = parseFloat(match[1]);
    const lng = parseFloat(match[2]);
    if (!isNaN(lat) && !isNaN(lng) && lat > 8 && lat < 24 && lng > 102 && lng < 110) {
      return [lat, lng];
    }
  }

  // 2. Tìm trong danh mục sân đã xác thực
  const normalized = locationStr.toLowerCase();
  for (const venue of VERIFIED_VENUES) {
    if (
      normalized.includes(venue.name.toLowerCase()) ||
      normalized.includes(venue.shortName.toLowerCase())
    ) {
      return [venue.lat, venue.lng];
    }
    // Tìm theo keywords
    if (venue.keywords && venue.keywords.some((kw) => normalized.includes(kw))) {
      return [venue.lat, venue.lng];
    }
  }

  return null;
}

// Xử lý tạo link mở chỉ đường Google Maps chính xác nhất
export function buildGoogleMapsDirectionsUrl(locationStr, coords) {
  // 1. Ưu tiên dùng tọa độ chính xác nếu có
  if (coords && coords[0] && coords[1]) {
    return `https://www.google.com/maps/dir/?api=1&destination=${coords[0]},${coords[1]}`;
  }

  // 2. Thử tìm tọa độ từ chuỗi
  const resolved = findVenueCoordinates(locationStr);
  if (resolved) {
    return `https://www.google.com/maps/dir/?api=1&destination=${resolved[0]},${resolved[1]}`;
  }

  // 3. Nếu không có tọa độ, dùng tên sân / địa chỉ sạch
  const cleanQuery = (locationStr || '')
    .replace(/Sân tại vị trí\s*\([^)]*\)/gi, '')
    .replace(/Vị trí bản đồ\s*\([^)]*\)/gi, '')
    .trim();

  return `https://www.google.com/maps/dir/?api=1&destination=${encodeURIComponent(cleanQuery || 'Hồ Chí Minh')}`;
}
